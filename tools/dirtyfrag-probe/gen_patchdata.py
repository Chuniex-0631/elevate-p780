"""Regenerate the Java constants from build/ artifacts and build/target.json."""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent
BUILD = ROOT / "build"
JAVA_DIR = ROOT / "probe-src" / "app" / "src" / "main" / "java" / "top" / "dcmqht" / "p780ipsec"


def lit(data: bytes) -> str:
    return "\n".join('        + "' + data[i:i + 64].hex() + '"' for i in range(0, len(data), 64))


def main() -> None:
    stub = (BUILD / "hook_stub.bin").read_bytes()
    entry = (BUILD / "hook_entry.bin").read_bytes()
    meta = json.loads((BUILD / "target.json").read_text(encoding="utf-8"))
    src = f'''package top.dcmqht.p780ipsec;

/** Generated by 21-dirtyfrag-probe-20261025/gen_patchdata.py - do not edit. */
final class PatchData {{
    static final String TARGET = "{meta['target']}";
    static final String LIB = "{meta['lib']}";
    static final int STUB_SITE = 0x{meta['victim']:x};
    static final int SENTRY = 0x{meta['entry']:x};
    static final String PROLOGUE_HEX = "{meta['prologue_hex']}";

    static final String STUB_HEX = ""
{lit(stub)};
    static final String ENTRY_HEX = ""
{lit(entry)};

    static byte[] stub() {{ return hexToBytes(STUB_HEX); }}
    static byte[] entry() {{ return hexToBytes(ENTRY_HEX); }}

    static byte[] hexToBytes(String hex) {{
        byte[] out = new byte[hex.length() / 2];
        for (int i = 0; i < out.length; i++) {{
            out[i] = (byte) Integer.parseInt(hex.substring(i * 2, i * 2 + 2), 16);
        }}
        return out;
    }}

    private PatchData() {{}}
}}
'''
    (JAVA_DIR / "PatchData.java").write_text(src, encoding="utf-8")
    print(f"PatchData.java: target={meta['target']} stub={len(stub)}B entry={len(entry)}B")


if __name__ == "__main__":
    main()
