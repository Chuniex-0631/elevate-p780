"""Generate text_syms.h / ro_syms.h for the P780 kernel (5.4.233) from kernel.kallsyms.

Format matches the pipa exploit: arrays of {offset_from_link_base, size} pairs,
sorted ascending, used for KASLR-leak validation by binary search.
"""
import re
from pathlib import Path

KALLSYMS = Path(r"C:\Users\ASUS Vivobook\Desktop\RakutenHand5G\27-symbol-recovery-20261025\P780-kernel-symbol-recovery\kernel.kallsyms")
OUT = Path(r"C:\Users\ASUS Vivobook\Desktop\RakutenHand5G\53-uring-cve-20261025\pipa")
LINK_BASE = 0xFFFFFFC010080000

line_re = re.compile(r"^([0-9a-fA-F]{16})\s+([a-zA-Z])\s+(.+)$")
syms = []
for line in KALLSYMS.read_text(encoding="utf-8", errors="replace").splitlines():
    m = line_re.match(line.strip())
    if not m:
        continue
    addr = int(m.group(1), 16)
    typ = m.group(2)
    name = m.group(3).strip()
    syms.append((addr, typ, name))

syms.sort()
# size = next symbol address - current (fallback 4)
entries = []
for i, (addr, typ, name) in enumerate(syms):
    nxt = syms[i + 1][0] if i + 1 < len(syms) else addr + 4
    size = max(1, nxt - addr)
    entries.append((addr, size, typ, name))

TEXT_TYPES = set("tTwW")
RO_TYPES = set("rR")


def emit(path, typ_set, guard):
    rows = [(a - LINK_BASE, s) for a, s, t, n in entries if t in typ_set and a >= LINK_BASE]
    rows.sort()
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write("/* auto-generated by gen_syms.py from kernel.kallsyms (P780 5.4.233) */\n")
        f.write(f"#ifndef {guard}\n#define {guard}\n")
        count_name = "TEXT_SYM_COUNT" if typ_set is TEXT_TYPES else "RO_SYM_COUNT"
        f.write(f"#define {count_name} {len(rows)}\n")
        f.write("static const unsigned int %s[] = {\n" % ("text_syms" if typ_set is TEXT_TYPES else "ro_syms"))
        line = []
        for off, size in rows:
            line.append(f"0x{off:x}, 0x{size:x}")
            if len(line) == 8:
                f.write("    " + ", ".join(line) + ",\n")
                line = []
        if line:
            f.write("    " + ", ".join(line) + ",\n")
        f.write("};\n#endif\n")
    print(path.name, len(rows))


emit(OUT / "text_syms.h", TEXT_TYPES, "TEXT_SYMS_H")
emit(OUT / "ro_syms.h", RO_TYPES, "RO_SYMS_H")
